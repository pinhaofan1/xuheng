import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.use({ baseURL: 'http://127.0.0.1:8011' })

test('AI job, historical citation, rejected evidence, history and report export', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://**', route => route.abort())
  await page.goto('/book/ai-browser-fixture/review/2')
  await expect(page.getByRole('button', { name: 'AI 深度审校', exact: true })).toBeEnabled()
  await page.getByRole('tab', { name: '历史检索', exact: true }).click()
  await page.getByRole('button', { name: '检索历史正文' }).click()
  await expect(page.locator('.history-pane blockquote')).toContainText('左臂已经断了')
  await expect(page.locator('.history-pane')).not.toContainText('未来章节')
  await page.getByRole('button', { name: 'AI 深度审校', exact: true }).click()
  await expect(page.getByText('浏览器测试响应，非真实模型结果。', { exact: true })).toBeVisible()
  await expect(page.locator('.finding')).toHaveCount(1)
  await expect(page.locator('.result-warning')).toContainText('未通过证据校验')
  await page.locator('.finding').click()
  await expect(page.locator('mark')).toHaveText('沈澜抬起左臂')
  await expect(page.locator('.source-card')).toContainText('历史原文 · 第 1 章')
  await expect(page.locator('.source-card blockquote')).toHaveText('左臂已经断了')
  await page.getByRole('button', { name: '确认问题', exact: true }).click()
  await expect(page.locator('.finding .status')).toHaveText('已确认')
  await page.reload()
  await expect(page.locator('.finding .status')).toHaveText('已确认')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出报告' }).click()
  const download = await downloaded
  const report = JSON.parse(await readFile((await download.path())!, 'utf-8'))
  expect(report.mode).toBe('ai')
  expect(report.issues).toHaveLength(1)
  expect(report.warnings).toHaveLength(1)
  expect(report.model_name).toBe('fixture-test-only')
  await page.getByRole('tab', { name: '运行历史', exact: true }).click()
  await expect(page.locator('.history-pane .finding')).toHaveCount(1)
  await page.locator('.history-pane .finding').click()
  await expect(page.locator('main.review-desk')).not.toContainText('PlotPilot')
  await page.screenshot({ path: '../project_docs/screenshots/full-ai-test-fixture.png', fullPage: true })
  await page.getByRole('link', { name: '关于与许可' }).click()
  await expect(page.getByText(/包含 PlotPilot 代码.*版权/)).toBeVisible()
  expect(errors).toEqual([])
})
