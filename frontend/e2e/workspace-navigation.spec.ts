import { test, expect } from '@playwright/test'

test.use({ baseURL: 'http://127.0.0.1:8011' })

test('library, manuscript-first editor, reference tools and review navigation', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://**', route => route.abort())
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '作品库', exact: true })).toBeVisible()
  await expect(page.locator('.library-book')).toHaveCount(1)
  await page.getByRole('button', { name: '检索模型', exact: true }).click()
  await page.getByRole('textbox', { name: '检索 API Key' }).fill('fixture-key-not-real')
  await page.getByRole('button', { name: '保存检索配置', exact: true }).click()
  await expect(page.getByText('检索配置已保存', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '检索 API Key' })).toHaveValue('')
  await page.keyboard.press('Escape')
  await page.getByRole('textbox', { name: '搜索作品', exact: true }).fill('不存在的作品')
  await expect(page.getByRole('heading', { name: '没有找到匹配的作品' })).toBeVisible()
  await page.getByRole('button', { name: '清除搜索', exact: true }).click()
  await page.getByRole('button', { name: '继续创作', exact: true }).click()
  await expect(page).toHaveURL(/\/book\/ai-browser-fixture\/workbench/)
  await expect(page.getByRole('textbox', { name: '章节内容...' })).toBeVisible()
  await expect(page.locator('.editor-title')).toContainText('断臂与潮声')
  await page.getByRole('button', { name: '人物设定', exact: true }).click()
  await expect(page.locator('.settings-tabs .n-tabs-tab--active').filter({ hasText: '作品设定' })).toBeVisible()
  await page.getByRole('button', { name: '更多工具', exact: true }).click()
  await page.getByText('伏笔账本', { exact: true }).last().click()
  await expect(page.locator('.settings-tabs .n-tabs-tab--active').filter({ hasText: '伏笔账本' })).toBeVisible()
  await page.goto('/book/ai-browser-fixture/review/2')
  await expect(page.locator('.rules-column')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '章节原文', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '审校设置', exact: true }).click()
  await page.getByRole('button', { name: '从作品人物库导入草稿', exact: true }).click()
  await expect(page.locator('.fact-tags')).toContainText('左臂受伤')
  await page.locator('.profile input').first().fill('未保存的改名')
  await page.getByRole('button', { name: '完成设置', exact: true }).click()
  await page.locator('.xh-chapter-nav a').first().click()
  await expect(page.getByText('人物设定尚未保存', { exact: true }).last()).toBeVisible()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(page).toHaveURL(/review\/2/)
  await page.locator('.xh-chapter-nav a').first().click()
  await page.getByRole('button', { name: '放弃并离开', exact: true }).click()
  await expect(page).toHaveURL(/review\/1/)
  await expect(page.getByRole('heading', { name: '章节原文', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: '展开工作区导航' }).click()
  await expect(page.locator('.xh-nav.is-open')).toBeVisible()
  await page.locator('.xh-nav-item').filter({ hasText: '人物与设定' }).click()
  await expect(page).toHaveURL(/panel=bible/)
  expect(errors).toEqual([])
})
