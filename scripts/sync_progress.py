"""Render the development board from one tracked source of truth.

Use --complete ID --evidence project_docs/RELEASE_x.y.md only after the item's
acceptance criteria have actually passed. CI checks consistency, not completion.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "project_docs/DEVELOPMENT_PROGRESS.json"
TARGET = ROOT / "project_docs/ROADMAP.md"
STATUSES = {"todo", "in_progress", "done", "optional"}
GROUPS = (("delivered", "已交付基线"), ("next", "后续开发与验收"), ("optional", "按需扩展"))


def evidence_path(value: str) -> Path:
    path = (ROOT / value).resolve()
    if not path.is_relative_to(ROOT) or not path.is_file():
        raise ValueError(f"验收依据必须是仓库内已有文件：{value}")
    if path.relative_to(ROOT).parts[0] not in {"project_docs", "tests", "frontend", ".github", "scripts"}:
        raise ValueError(f"请使用验收文档或测试文件作为依据：{value}")
    return path


def validate(data: dict) -> None:
    ids = set()
    for item in data["items"]:
        if item["id"] in ids:
            raise ValueError(f"重复编号：{item['id']}")
        ids.add(item["id"])
        if item["status"] not in STATUSES or item["group"] not in {g for g, _ in GROUPS}:
            raise ValueError(f"无效状态或分组：{item['id']}")
        if not item["title"].strip() or not item["acceptance"].strip():
            raise ValueError(f"缺少功能名称或验收标准：{item['id']}")
        if item["status"] == "done" and (not item.get("completed_at") or not item["evidence"]):
            raise ValueError(f"完成项必须有完成日期和验收依据：{item['id']}")
        for evidence in item["evidence"]:
            evidence_path(evidence)
    evidence_path(data["baseline"]["evidence"])
    order = data.get("next_order", [])
    if len(order) != len(set(order)) or any(item_id not in ids for item_id in order):
        raise ValueError("推荐顺序包含重复或未知编号")


def cell(value: str) -> str:
    return value.replace("|", "&#124;").replace("\n", "<br>")


def render(data: dict) -> str:
    items = data["items"]
    done = sum(item["status"] == "done" for item in items)
    pending = sum(item["group"] == "next" and item["status"] != "done" for item in items)
    optional = sum(item["group"] == "optional" and item["status"] != "done" for item in items)
    baseline = data["baseline"]
    by_id = {item["id"]: item for item in items}
    remaining_order = [item_id for item_id in data.get("next_order", []) if by_id[item_id]["status"] != "done"]
    lines = ["# 开发进度表", "", "<!-- Generated by scripts/sync_progress.py. Edit DEVELOPMENT_PROGRESS.json instead. -->", "",
        f"当前版本：**{data['version']}**；更新日期：**{data['updated_at']}**。",
        f"已完成 **{done} 项**，下一阶段待完成 **{pending} 项**，按需扩展 **{optional} 项**。该计数只表示清单条目数量。", "",
        f"验证基线：单元测试 {baseline['unit_passed']} 项通过、{baseline['unit_skipped']} 项跳过；浏览器场景 {baseline['browser_passed']} 项通过。"
        f"范围见 [交付记录]({Path(baseline['evidence']).name})；远端 CI 以 GitHub Actions 为准。", "",
        "☑ 表示实现且通过对应验收；☐ 表示未完成。优先顺序为 P0 → P1 → P2；进行中保持未勾选，按需项单独安排。", ""]
    if remaining_order:
        first = by_id[remaining_order[0]]
        lines.extend([f"**建议下一项：{first['id']} · {first['title']}。** 最近一批顺序：{' → '.join(remaining_order[:4])}；已完成条目自动跳过。", ""])
    for group, label in GROUPS:
        lines.extend([f"## {label}", "", "| 完成 | 编号 | 优先级 | 功能 / 验收项 | 状态 | 完成标准 | 验收依据 |",
                      "| --- | --- | --- | --- | --- | --- | --- |"])
        for item in items:
            if item["group"] != group:
                continue
            status = {"done": "已完成", "in_progress": "进行中", "optional": "按需启动"}.get(item["status"],
                "待验收" if item.get("kind") == "verification" else "待开发")
            evidence = "、".join(f"[依据 {index}](../{path})" for index, path in enumerate(item["evidence"], 1)) or "—"
            if item["status"] == "done":
                evidence += f"<br>{item['completed_at']}"
            values = ["☑" if item["status"] == "done" else "☐", item["id"], item["priority"], item["title"], status, item["acceptance"], evidence]
            lines.append("| " + " | ".join(cell(v) for v in values) + " |")
        lines.append("")
    lines.extend(["## 更新规则", "",
        "进度数据保存在 [DEVELOPMENT_PROGRESS.json](DEVELOPMENT_PROGRESS.json)。后续开发完成并通过对应验收后，由开发助手在同一轮更新状态、验收依据和完成日期，脚本自动生成本表的勾选。CI 检查数据与表格一致。", "",
        "```powershell", "# 开始一项工作", "python scripts/sync_progress.py --start F04", "",
        "# 验收通过后完成勾选；依据文件须已存在", "python scripts/sync_progress.py --complete F04 --evidence project_docs/RELEASE_0.7.md", "",
        "# 校验进度表与数据一致", "python scripts/sync_progress.py --check", "```", "",
        "验收项需对应的运行或人工评测记录；测试通过数不能替代完整长跑或真实质量评估。新增需求先增加独立条目及验收标准，已有编号保持稳定。", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--check", action="store_true")
    action.add_argument("--start", metavar="ID")
    action.add_argument("--complete", metavar="ID")
    parser.add_argument("--evidence", action="append", default=[], help="仓库内验收依据路径，可重复填写")
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    validate(data)
    if args.evidence and not args.complete:
        parser.error("--evidence 与 --complete 一起使用")
    if args.start or args.complete:
        item = next((i for i in data["items"] if i["id"] == (args.start or args.complete)), None)
        if item is None:
            parser.error("未找到该条目编号")
        today = datetime.now(timezone(timedelta(hours=8))).date().isoformat()
        if args.complete:
            if not args.evidence:
                parser.error("完成勾选需要 --evidence 指向验收依据")
            item["evidence"] = [evidence_path(p).relative_to(ROOT).as_posix() for p in args.evidence]
            item.update(status="done", completed_at=today)
        else:
            if item["status"] == "done":
                parser.error("已完成条目不能用 --start 重置；新工作请添加独立条目")
            item["status"] = "in_progress"
        data["updated_at"] = today
        validate(data)
    result = render(data)
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != result:
            parser.exit(1, "开发进度表未同步，请运行 python scripts/sync_progress.py\n")
        print("Development progress board is consistent.")
    else:
        if args.start or args.complete:
            SOURCE.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        TARGET.write_text(result, encoding="utf-8")
        print("Updated project_docs/ROADMAP.md")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError) as exc:
        sys.exit(str(exc))
